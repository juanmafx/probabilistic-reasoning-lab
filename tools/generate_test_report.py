# Runs the test suite and writes a sanitized JUnit report plus a Markdown summary.
from __future__ import annotations

import platform
import subprocess
import sys
import xml.etree.ElementTree as ElementTree
from datetime import UTC, datetime
from importlib.metadata import version
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPORT_DIRECTORY = ROOT / "reports" / "tests"
JUNIT_PATH = REPORT_DIRECTORY / "junit.xml"
SUMMARY_PATH = REPORT_DIRECTORY / "summary.md"


def run_tests() -> int:
    command = [
        sys.executable,
        "-m",
        "pytest",
        "-p",
        "no:cacheprovider",
        f"--junitxml={JUNIT_PATH}",
        "-o",
        "junit_family=xunit2",
    ]
    return subprocess.run(command, cwd=ROOT, check=False).returncode


def sanitize_report() -> ElementTree.Element:
    tree = ElementTree.parse(JUNIT_PATH)
    root = tree.getroot()
    for suite in root.iter("testsuite"):
        suite.attrib.pop("hostname", None)
    tree.write(JUNIT_PATH, encoding="utf-8", xml_declaration=True)
    return next(root.iter("testsuite"))


def write_summary(suite: ElementTree.Element, exit_code: int) -> None:
    total = int(suite.attrib["tests"])
    failed = int(suite.attrib["failures"]) + int(suite.attrib["errors"])
    skipped = int(suite.attrib["skipped"])
    lines = [
        "# Test Report",
        "",
        "Generated by `tools/generate_test_report.py` from an actual local run.",
        "",
        "| Field | Value |",
        "| --- | --- |",
        f"| Generated at (UTC) | {datetime.now(UTC).strftime('%Y-%m-%d %H:%M:%S')} |",
        f"| Python | {platform.python_version()} |",
        f"| pytest | {version('pytest')} |",
        f"| Hypothesis | {version('hypothesis')} (derandomized profile) |",
        f"| Tests | {total} |",
        f"| Passed | {total - failed - skipped} |",
        f"| Failed or errored | {failed} |",
        f"| Skipped | {skipped} |",
        f"| Duration (seconds) | {float(suite.attrib['time']):.2f} |",
        f"| pytest exit code | {exit_code} |",
        "",
        "Raw results are in `junit.xml`.",
        "",
    ]
    SUMMARY_PATH.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    REPORT_DIRECTORY.mkdir(parents=True, exist_ok=True)
    JUNIT_PATH.unlink(missing_ok=True)
    SUMMARY_PATH.unlink(missing_ok=True)
    exit_code = run_tests()
    if not JUNIT_PATH.exists():
        return exit_code or 1
    write_summary(sanitize_report(), exit_code)
    return exit_code


if __name__ == "__main__":
    raise SystemExit(main())
